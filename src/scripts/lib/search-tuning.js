// Настройка поиска Pagefind — общая для сайта (search.js) и проверки выдачи (tools/search-check.mjs).

// Статья, главная по слову запроса (searchMain в site.config.ts → мета-поле keys), встаёт первой:
// совпадение в keys весит как совпадение в заголовке (у title вес 5 по умолчанию).
export const ranking = { metaWeights: { keys: 5 } };

// Разговорные слова → те, что написаны в статьях: «физра» и «физкультура» должны давать одну и ту же выдачу.
// Слово ищется целиком, вместе с окончанием: «общаги», «в общагу». \b в JS не знает кириллицу, поэтому границы
// слова заданы явно.
const word = (stem, to, ending = "[а-яё]*") => [new RegExp(`(^|[^а-яё])${stem}${ending}(?![а-яё])`, "gi"), `$1${to}`];

const slang = [
  word("физ-?р", "физкультура"),
  word("общаг", "общежитие"),
  word("стипух", "стипендия"),
  word("вступиталк", "вступительные"),
  word("допс", "пересдача"),               // допса, допсессия
  word("хвост", "задолженность"),
  word("при[её]мк", "приёмная комиссия"),
  word("лк", "личный кабинет", ""),
  word("вай-?фай", "wi-fi", ""),
];

export const plain = (query) => slang.reduce((text, [re, to]) => text.replace(re, to), query);
